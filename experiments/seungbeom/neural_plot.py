"""Plot a completed neural experiment's saved history; no competition inputs are opened."""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path


def read_history(run_dir: Path):
    """Read only the four explicitly named report files in the supplied run directory."""
    run_dir = Path(run_dir)
    status = json.loads((run_dir / "status.json").read_text(encoding="utf-8"))
    if status.get("status") != "complete":
        raise ValueError("Run must be complete before plotting its best checkpoint.")
    config = json.loads((run_dir / "config.json").read_text(encoding="utf-8"))
    best = json.loads((run_dir / "best_metrics.json").read_text(encoding="utf-8"))
    history = json.loads((run_dir / "history.json").read_text(encoding="utf-8"))["epochs"]
    if not history:
        raise ValueError("History must contain at least one completed epoch.")
    epochs = [row["epoch"] for row in history]
    if any(type(epoch) is not int or epoch < 1 for epoch in epochs):
        raise ValueError("History epochs must be positive integers.")
    if any(right <= left for left, right in zip(epochs, epochs[1:], strict=False)):
        raise ValueError("History epochs must be strictly increasing.")
    if best.get("epoch") not in epochs:
        raise ValueError("The best checkpoint epoch is absent from history.")
    for row in history:
        for name in ("train_loss", "validation_ce_loss", "macro_f1"):
            value = row[name]
            if type(value) not in (int, float) or not math.isfinite(value) or value < 0:
                raise ValueError("History losses and metrics must be finite and nonnegative.")
        scores = [row["macro_f1"], *[row["class_f1"][str(label)] for label in range(1, 7)]]
        if any(
            type(score) not in (int, float) or not math.isfinite(score) or not 0 <= score <= 1
            for score in scores
        ):
            raise ValueError("History F1 metrics must be finite and in [0, 1].")
    return config, best, history


def plot_history(run_dir: Path, output: Path) -> Path:
    output = Path(output)
    if output.exists():
        raise ValueError("Output already exists. Choose a new plot filename.")
    if output.suffix.lower() not in {".png", ".pdf", ".svg"}:
        raise ValueError("Plot output must use .png, .pdf, or .svg.")
    config, best, history = read_history(Path(run_dir))
    # Matplotlib is optional; neither CLI help nor numeric validation imports it.
    import matplotlib

    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    epochs = [row["epoch"] for row in history]
    fig, axes = plt.subplots(2, 2, figsize=(12, 8), layout="constrained")
    objective = config.get("loss", "cross_entropy")
    titles = (
        f"Train loss ({objective})",
        "Validation loss (unweighted CE)",
        "Validation Macro F1",
        "Validation F1 by class",
    )
    colors = ("#2563eb", "#dc2626", "#0f766e")
    for axis, key, title, color in zip(
        axes.flat,
        ("train_loss", "validation_ce_loss", "macro_f1"),
        titles,
        colors,
        strict=False,
    ):
        axis.plot(
            epochs,
            [row[key] for row in history],
            color=color,
            linewidth=2,
            marker="o",
            markersize=3,
        )
        axis.set_title(title, loc="left", fontsize=11, fontweight="bold")
        axis.set_ylabel("F1" if key == "macro_f1" else "Loss")
    class_axis = axes[1, 1]
    for label in range(1, 7):
        class_axis.plot(
            epochs,
            [row["class_f1"][str(label)] for row in history],
            linewidth=1.8,
            label=f"Class {label}",
        )
    class_axis.set_title(titles[3], loc="left", fontsize=11, fontweight="bold")
    class_axis.set_ylabel("F1")
    for axis in axes.flat:
        axis.axvline(
            best["epoch"],
            color="#475569",
            linestyle="--",
            linewidth=1.2,
            label=f"Best epoch: {best['epoch']}",
        )
        axis.set_xlabel("Epoch")
        axis.grid(True, alpha=0.2)
        axis.spines[["top", "right"]].set_visible(False)
        axis.set_xlim(max(0.5, epochs[0] - 0.5), epochs[-1] + 0.5)
    axes[1, 0].set_ylim(0, 1.02)
    axes[1, 1].set_ylim(0, 1.02)
    axes[1, 0].legend(loc="lower right", fontsize=8, frameon=False)
    class_axis.legend(loc="lower right", ncol=2, fontsize=8, frameon=True)
    title = (
        f"Neural experiment: {config.get('encoder', 'unknown')} / "
        f"{config.get('fusion', 'unknown')} / seed {config.get('seed', '?')}"
    )
    fig.suptitle(title + "\nValidation is used for checkpoint selection.", fontsize=13)
    output.parent.mkdir(parents=True, exist_ok=True)
    try:
        # Exclusive creation preserves a report generated by another process.
        with output.open("xb") as handle:
            fig.savefig(handle, format=output.suffix[1:].lower(), dpi=160)
    finally:
        plt.close(fig)
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run_dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    path = plot_history(args.run_dir, args.output)
    print("Saved neural learning curves:", path)


if __name__ == "__main__":
    main()
